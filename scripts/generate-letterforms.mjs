// Generates SVG letterform paths for the hero "plotter" entrance.
// Run: npm run generate:letterforms  (only needed if the name or typeface changes)
import fs from "node:fs";
// fontkit 2.x's Node ESM entry (dist/module.mjs) only provides named exports
// (no default export), unlike its CJS entry — `import fontkit from "fontkit"`
// throws under this package's "type": "module". Namespace-import instead.
import * as fontkit from "fontkit";

const CANDIDATES = [
  "node_modules/@fontsource-variable/archivo/files/archivo-latin-wdth-normal.woff2",
  "node_modules/@fontsource-variable/archivo/files/archivo-latin-full-normal.woff2",
  "node_modules/@fontsource-variable/archivo/files/archivo-latin-standard-normal.woff2",
];
const file = CANDIDATES.find((f) => fs.existsSync(f));
if (!file) {
  console.error("No Archivo variable font file found under node_modules/@fontsource-variable/archivo/files/");
  console.error("Available:", fs.readdirSync("node_modules/@fontsource-variable/archivo/files/").join("\n"));
  process.exit(1);
}

let font = fontkit.openSync(file);
try {
  if (font.variationAxes && Object.keys(font.variationAxes).length > 0) {
    const varied = font.getVariation({ wght: 780, wdth: 120 });
    // fontkit's getVariation() rebuilds a plain TTFFont by reading raw bytes
    // from `this.stream.buffer` at the original sfnt directory offset. That
    // assumption holds for plain TTF/OTF sources, but not for WOFF2 sources
    // (this font's buffer is WOFF2-compressed/transformed, not a raw sfnt
    // directory), so the returned instance can look valid yet fail once its
    // tables are actually touched. getVariation() itself doesn't throw in
    // that case — the failure only surfaces on first real use — so probe it
    // with a real layout call here, inside the try, before committing to it.
    const probe = varied.layout("A");
    if (!probe.glyphs[0] || !probe.glyphs[0].path.toSVG()) {
      throw new Error("variation instance produced an empty glyph path");
    }
    font = varied;
  }
} catch (err) {
  console.warn("Variation instancing failed; using default instance:", err.message);
}

const LINES = ["RAHUL", "SHARMA"];
const lines = LINES.map((text) => {
  const run = font.layout(text);
  let x = 0;
  const glyphs = [];
  run.glyphs.forEach((g, i) => {
    const pos = run.positions[i];
    glyphs.push({ d: g.path.toSVG(), x: x + (pos.xOffset || 0) });
    x += pos.xAdvance;
  });
  return { glyphs, width: x };
});

const out = `// GENERATED by scripts/generate-letterforms.mjs — DO NOT EDIT BY HAND.
// Regenerate with: npm run generate:letterforms
export type PlottedGlyph = { d: string; x: number };
export type PlottedLine = { glyphs: PlottedGlyph[]; width: number };
export const plottedName = ${JSON.stringify(
  { lines, unitsPerEm: font.unitsPerEm, ascent: font.ascent, descent: font.descent },
  null,
  2
)} as const;
`;
fs.mkdirSync("src/generated", { recursive: true });
fs.writeFileSync("src/generated/letterforms.ts", out);
console.log(
  "Wrote src/generated/letterforms.ts —",
  lines.map((l, i) => `${LINES[i]}: ${l.glyphs.length} glyphs, width ${l.width}`).join(" | "),
  `— upm ${font.unitsPerEm}`
);
